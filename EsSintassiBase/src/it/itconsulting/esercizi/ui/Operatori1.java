package it.itconsulting.esercizi.ui;

public class Operatori1 {

	public static void main(String[] args) {
		byte a=-2;
		short b=25;
		int c=32;
		long d=255l;
		float e=15.32f;
		double f=254.78d;
		char g='A';
		boolean h=true;
		System.out.println("Il valore della variabile a è: "+ a);
		System.out.println("Il valore della variabile b è: "+ b);
		System.out.println("Il valore della variabile c è: "+ c);
		System.out.println("Il valore della variabile d è: "+ d);
		System.out.println("Il valore della variabile e è: "+ e);
		System.out.println("Il valore della variabile f è: "+ f);
		System.out.println("Il valore della variabile g è: "+ g);
		System.out.println("Il valore della variabile h è: "+ h);

		
	}

}
